package com.vaadin.tutorial.addressbook.backend;

import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.time.LocalDate;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.TimeZone;
import java.util.function.Function;
import java.util.stream.Collectors;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.function.Executable;

/**
 * The demo data is what baseline runs and workflows compare against: the 100 contacts from
 * {@code Random(0)} must match the old app's, in id order. {@code demo-contacts.csv} was generated by
 * the old app's {@code ContactService} in UTC and en-US; surefire runs the tests in the same time zone
 * and locale (pom.xml), and the guard below fails if they are run another way.
 */
class DemoDataTest {

    private static final String HEADER = "id,firstName,lastName,email,phone,birthDate";

    @BeforeAll
    static void runsInUtcAndEnUs() {
        assertEquals("UTC", TimeZone.getDefault().getID(),
                "time zone: run with -Duser.timezone=UTC (mvn test sets it)");
        assertEquals(Locale.US, Locale.getDefault(),
                "locale: run with -Duser.language=en -Duser.country=US (mvn test sets it)");
    }

    private static String row(Contact c) {
        LocalDate born = c.getBirthDate().toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
        return String.join(",", String.valueOf(c.getId()), c.getFirstName(), c.getLastName(), c.getEmail(),
                c.getPhone(), born.toString());
    }

    private static List<String> expectedRows() throws IOException {
        List<String> rows = new ArrayList<>();
        try (InputStream in = DemoDataTest.class.getResourceAsStream("demo-contacts.csv")) {
            assertNotNull(in, "demo-contacts.csv on the test classpath");
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            for (String line = reader.readLine(); line != null; line = reader.readLine()) {
                if (!line.isEmpty() && !line.startsWith("#")) {
                    rows.add(line);
                }
            }
        }
        assertEquals(HEADER, rows.remove(0), "demo-contacts.csv header");
        return rows;
    }

    private static List<String> actualRows() {
        List<Contact> all = new ArrayList<>(ContactService.createDemoService().findAll(null));
        all.sort(Comparator.comparing(Contact::getId));
        return all.stream().map(DemoDataTest::row).collect(Collectors.toList());
    }

    @Test
    void theHundredDemoContactsMatchTheOldApp() throws IOException {
        List<String> expected = expectedRows();
        List<String> actual = actualRows();
        assertEquals(100, expected.size(), "rows in demo-contacts.csv");
        assertEquals(100, actual.size(), "demo contacts from findAll");
        List<Executable> checks = new ArrayList<>();
        for (int i = 0; i < expected.size(); i++) {
            String want = expected.get(i);
            String got = actual.get(i);
            checks.add(() -> assertEquals(want, got));
        }
        assertAll("demo contacts in id order (id,firstName,lastName,email,phone,birthDate)", checks);
    }

    /** Day 0 rolls back to the last day of the previous month (RL-09, BR-08). */
    @Test
    void dayZeroBirthDatesRollBackToThePreviousMonth() {
        Function<Long, Contact> byId = id -> ContactService.createDemoService().findAll(null).stream()
                .filter(c -> c.getId().equals(id)).findFirst().orElseThrow();
        assertAll(
                () -> assertEquals("7,Daniel,Anderson,daniel@anderson.com,+ 358 555 398,1931-06-30", row(byId.apply(7L))),
                () -> assertEquals("11,Rene,King,rene@king.com,+ 358 555 458,1968-05-31", row(byId.apply(11L))),
                () -> assertEquals("60,Linda,King,linda@king.com,+ 358 555 812,1939-03-31", row(byId.apply(60L))),
                () -> assertEquals("88,Daniel,Robinson,daniel@robinson.com,+ 358 555 244,1952-12-31", row(byId.apply(88L))));
    }
}
